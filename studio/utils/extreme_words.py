import re

# 平台广告法禁用之极限词列表
EXTREME_WORDS = [
    # 1. 绝对性词汇
    "第一", "最", "最高", "最低", "最好", "最大", "最小", "最强", "最差", "最先", "最后", "最新",
    "顶级", "顶尖", "极致", "极品", "终极", "巅峰", "至尊", "绝对", "极致", "冠", "首", "之首",
    "最前沿", "最先进", "最符合", "最热", "最划算", "最高级", "最顶级", "终极", "空前绝后",
    # 2. 国家级/行业权威性词汇
    "国家级", "国级", "世界级", "宇宙级", "全球级", "特级", "金牌", "名牌", "优秀", "权威", "免检",
    # 3. 独家/排他性词汇
    "唯一", "独家", "独一无二", "首发", "全网首发", "全网第一", "独创", "首创", "仅此一次",
    "仅此一家", "首选", "第一品牌", "独占", "垄断", "绝对性", "绝无仅有",
    # 4. 虚假/欺诈性保障词汇
    "100%", "百分之百", "保证", "保证通过", "包过", "神效", "特效", "神级", "立刻见效",
    "万能", "绝对安全", "无毒", "无副作用", "纯天然", "百分之百天然", "纯绿色", "绿色天然",
    # 5. 电商促销敏感词汇
    "全网最低", "全网最低价", "低价", "破产价", "秒杀", "点击领奖", "无效退款", "省钱", "赚大钱",
    "发财", "致富", "暴富"
]

def check_extreme_words(text: str) -> list[dict]:
    """
    检测文本中的极限词。
    返回结构: [{"word": "最", "start": 12, "end": 13}, ...]
    """
    results: list[dict] = []
    if not text:
        return results

    for word in EXTREME_WORDS:
        escaped_word = re.escape(word)
        # 用 finditer 查找所有出现的位置，不区分大小写
        for match in re.finditer(escaped_word, text, re.IGNORECASE):
            results.append({
                "word": word,
                "start": match.start(),
                "end": match.end()
            })

    # 按出现顺序排序
    results.sort(key=lambda x: int(x["start"]))
    return results
